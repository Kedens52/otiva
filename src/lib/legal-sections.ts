/** Якоря разделов для поиска и содержания (подписи совпадают с заголовками h2 на странице). */

export type LegalSectionRef = { id: string; label: string }

function slug(label: string, index: number) {
  const base = label
    .toLowerCase()
    .replace(/^\d+\.\s*/, "")
    .replace(/[^a-zа-яё0-9\s-]/gi, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 56)
  return base || `section-${index}`
}

function sections(labels: string[]): LegalSectionRef[] {
  return labels.map((label, i) => ({ id: slug(label, i), label }))
}

